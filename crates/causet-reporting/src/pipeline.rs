//! The pipeline that turns reports into records: dedupe, rate limits,
//! sampling and metric aggregation.

use std::collections::{BTreeMap, HashMap, VecDeque};
use std::fmt::{self, Write as _};
use std::hash::{Hash, Hasher};
use std::sync::Arc;
use std::time::{SystemTime, UNIX_EPOCH};

use crate::config::{Config, MetricAggregateConfig, MetricPolicy};
use crate::types::{
    AcceptOutcome, AcceptStats, Object, Payload, PayloadBuilder, Record, Report, ReportKind,
    Source, Value,
};

/// Runtime state, built only by `new`: it is not serializable, since its
/// policy index, record IDs and run identity come from construction. Persist
/// `config` and `stats` instead.
///
/// ```compile_fail
/// fn restorable<T: serde::de::DeserializeOwned>() {}
/// restorable::<causet_reporting::Pipeline>();
/// ```
#[derive(Clone, Debug)]
pub struct Pipeline {
    /// Read on every report. Metric policies are indexed by `new`, so a
    /// change to `metrics` afterwards has no effect; the other sections apply
    /// at once.
    pub config: Config,
    /// Reports accepted and dropped so far, by reason.
    pub stats: AcceptStats,
    rate_limits: HashMap<Source, VecDeque<u64>>,
    /// Each key's last sighting and the generation of its newest entry in
    /// `dedupe_order`. A queue entry evicts its key only while it is that
    /// newest entry: sightings at the same millisecond are told apart.
    dedupe: HashMap<SeenKey, (u64, u64)>,
    dedupe_order: VecDeque<(u64, u64, SeenKey)>,
    dedupe_generation: u64,
    /// One window per metric policy that aggregates, in source and event
    /// order, the order they flush in. Policies point into it by index.
    aggregates: Vec<Aggregate>,
    metric_policy_index: HashMap<Source, HashMap<String, MetricPolicyResolved>>,
    next_id: u64,
    run_id: Arc<str>,
}

impl Pipeline {
    /// A pipeline with nothing seen yet and a run ID taken from the clock.
    pub fn new(config: Config) -> Self {
        let (metric_policy_index, aggregates) = build_metric_policies(&config);
        Self {
            config,
            rate_limits: HashMap::new(),
            dedupe: HashMap::new(),
            dedupe_order: VecDeque::new(),
            dedupe_generation: 0,
            aggregates,
            metric_policy_index,
            stats: AcceptStats::default(),
            next_id: 1,
            run_id: generate_run_id(),
        }
    }

    /// Accept a report as a record without applying sampling or further aggregation.
    ///
    /// Intended for reports generated by the pipeline itself (e.g. flushed metric aggregates).
    pub fn accept_aggregate_report(&mut self, now_ms: u64, report: Report) -> Option<Record> {
        self.accept_report_internal(now_ms, report)
    }

    /// Whether `config.enabled` is set.
    pub fn is_enabled(&self) -> bool {
        self.config.enabled
    }

    /// The configuration in use.
    pub fn config(&self) -> &Config {
        &self.config
    }

    /// Tells this pipeline's records from another run's: the nanoseconds since
    /// the Unix epoch at `new`, in base62. Only the first record carries it.
    pub fn run_id(&self) -> Arc<str> {
        self.run_id.clone()
    }
    /// Clears `out`, then fills it with a `metric_aggregate` report for each
    /// window that has lasted its `window_ms` by `now_ms` and holds data, in
    /// source and event order, and starts every window that has lasted that
    /// long again at `now_ms`. While disabled it only clears `out`. The
    /// reports are not records yet: pass them to `accept_aggregate_report`.
    pub fn flush_aggregates_into(&mut self, now_ms: u64, out: &mut Vec<Report>) {
        out.clear();
        self.flush_aggregates_at(now_ms, out);
    }

    /// Feeds `report` to its metric policy's aggregation, then runs it through
    /// dedupe, the rate limit and sampling at `now_ms`, counting the outcome in
    /// `stats`. The outcome holds the record if the report was kept, and the
    /// aggregate of a window the report closed, which skips sampling.
    ///
    /// The report's hashes are computed only when a step reads them: dedupe
    /// (the dedupe key's hash, or the payload's), sampling at a rate strictly
    /// between 0 and 1, and a full reservoir (the payload's).
    pub fn accept_report(&mut self, now_ms: u64, report: Report) -> AcceptOutcome {
        let mut outcome = AcceptOutcome::default();
        if !self.config.enabled {
            self.stats.dropped_disabled = self.stats.dropped_disabled.saturating_add(1);
            return outcome;
        }

        let policy = self.metric_policy(&report);
        let mut hashes = ReportHashes::default();
        if let Some(aggregate_report) =
            self.maybe_aggregate_metric(now_ms, &report, policy, &mut hashes)
            && let Some(record) = self.accept_report_internal(now_ms, aggregate_report)
        {
            outcome.aggregate = Some(record);
        }

        outcome.record = self.accept_report_with_hashes(now_ms, report, policy, hashes, false);
        outcome
    }

    /// Dedupe and the rate limit, without sampling.
    fn accept_report_internal(&mut self, now_ms: u64, report: Report) -> Option<Record> {
        self.accept_report_with_hashes(now_ms, report, None, ReportHashes::default(), true)
    }

    fn accept_report_with_hashes(
        &mut self,
        now_ms: u64,
        report: Report,
        policy: Option<MetricPolicyResolved>,
        mut hashes: ReportHashes,
        skip_sampling: bool,
    ) -> Option<Record> {
        if self.should_dedupe(&report.kind) {
            let Some(hash) = hashes.dedupe(&report) else {
                self.stats.dropped_invalid = self.stats.dropped_invalid.saturating_add(1);
                return None;
            };
            let key = SeenKey {
                kind: report.kind,
                hash,
            };
            if !self.check_dedupe(now_ms, key) {
                self.stats.dropped_deduped = self.stats.dropped_deduped.saturating_add(1);
                return None;
            }
        }

        if !self.check_rate_limit(now_ms, &report) {
            self.stats.dropped_rate_limited = self.stats.dropped_rate_limited.saturating_add(1);
            return None;
        }

        if !skip_sampling {
            let rate = policy
                .and_then(|policy| policy.sample_rate)
                .unwrap_or_else(|| self.config.sampling.rate_for(&report.kind));
            let kept = if rate >= 1.0 {
                true
            } else if rate <= 0.0 {
                false
            } else {
                let Some(hash) = hashes.payload(&report) else {
                    self.stats.dropped_invalid = self.stats.dropped_invalid.saturating_add(1);
                    return None;
                };
                sampled_in(rate, &hash)
            };
            if !kept {
                self.stats.dropped_sampled = self.stats.dropped_sampled.saturating_add(1);
                return None;
            }
        }

        self.stats.accepted = self.stats.accepted.saturating_add(1);

        let id = self.next_id;
        self.next_id = self.next_id.saturating_add(1);

        Some(Record {
            id,
            timestamp_ms: now_ms,
            report,
            run_id: if id == 1 {
                Some(self.run_id.clone())
            } else {
                None
            },
        })
    }

    fn flush_aggregates_at(&mut self, now_ms: u64, out: &mut Vec<Report>) {
        if !self.config.enabled {
            return;
        }

        for Aggregate { key, config, state } in &mut self.aggregates {
            let Some(window_start) = state.window_start_ms else {
                continue;
            };
            if now_ms.saturating_sub(window_start) < config.window_ms {
                continue;
            }

            if state.has_data() {
                out.push(state.build_report(key, window_start, config.window_ms));
            }
            state.reset(now_ms);
        }
    }

    fn check_dedupe(&mut self, now_ms: u64, key: SeenKey) -> bool {
        let window_ms = self.config.dedupe.window_ms;
        while let Some(&(seen_ms, _, _)) = self.dedupe_order.front() {
            if now_ms.saturating_sub(seen_ms) <= window_ms {
                break;
            }
            self.evict_front();
        }

        let generation = self.dedupe_generation;
        self.dedupe_generation = generation.wrapping_add(1);
        let duplicate = match self.dedupe.insert(key, (now_ms, generation)) {
            Some((prev_ms, _)) => now_ms.saturating_sub(prev_ms) <= window_ms,
            None => false,
        };
        self.dedupe_order.push_back((now_ms, generation, key));
        while self.dedupe_order.len() > self.config.dedupe.max_entries {
            self.evict_front();
        }
        !duplicate
    }

    /// Drops the oldest queue entry, and its key with it if no newer
    /// sighting of that key is queued.
    fn evict_front(&mut self) {
        if let Some((_, generation, key)) = self.dedupe_order.pop_front()
            && let std::collections::hash_map::Entry::Occupied(entry) = self.dedupe.entry(key)
            && entry.get().1 == generation
        {
            entry.remove();
        }
    }
    fn check_rate_limit(&mut self, now_ms: u64, report: &Report) -> bool {
        let window_ms = self.config.rate_limit.window_ms;
        let max_per_window = self.config.rate_limit.max_per_window as usize;

        let entry = self.rate_limits.entry(report.source).or_default();

        while let Some(front) = entry.front() {
            if now_ms.saturating_sub(*front) <= window_ms {
                break;
            }
            entry.pop_front();
        }

        if entry.len() >= max_per_window {
            return false;
        }

        entry.push_back(now_ms);
        true
    }

    /// The metric policy of a metric or event report, looked up once per
    /// report: sampling and aggregation both read it.
    fn metric_policy(&self, report: &Report) -> Option<MetricPolicyResolved> {
        if !matches!(report.kind, ReportKind::Metric | ReportKind::Event) {
            return None;
        }
        let event = report.payload.event_str()?;
        self.metric_policy_index
            .get(&report.source)
            .and_then(|inner| inner.get(event))
            .copied()
    }

    fn maybe_aggregate_metric(
        &mut self,
        now_ms: u64,
        report: &Report,
        policy: Option<MetricPolicyResolved>,
        hashes: &mut ReportHashes,
    ) -> Option<Report> {
        let Aggregate { key, config, state } = self.aggregates.get_mut(policy?.aggregate?)?;
        let payload = &report.payload;

        let has_value = config
            .fields
            .iter()
            .any(|field| payload.field_value(field).and_then(Value::as_f64).is_some());
        let has_group = config
            .group_by
            .iter()
            .any(|field| payload.field_value(field).is_some());
        if !has_value && !has_group {
            return None;
        }

        let should_flush = state
            .window_start_ms
            .map(|start| now_ms.saturating_sub(start) >= config.window_ms)
            .unwrap_or(false);

        let report_out = if should_flush {
            if state.has_data() {
                let window_start = state.window_start_ms.unwrap_or(now_ms);
                let report = state.build_report(key, window_start, config.window_ms);
                state.reset(now_ms);
                Some(report)
            } else {
                state.reset(now_ms);
                None
            }
        } else {
            if state.window_start_ms.is_none() {
                state.window_start_ms = Some(now_ms);
            }
            None
        };

        let mut hash = || hashes.payload(report);
        for field in &config.fields {
            if let Some(value) = payload.field_value(field).and_then(Value::as_f64) {
                state.record_field(field, value, &mut hash, config.samples);
            }
        }
        for field in &config.group_by {
            if let Some(value) = payload.field_value(field) {
                with_group_text(payload, value, |text| {
                    state.record_group(field, text, config.max_groups)
                });
            }
        }

        report_out
    }

    fn should_dedupe(&self, kind: &ReportKind) -> bool {
        if !self.config.dedupe.enabled {
            return false;
        }
        match kind {
            ReportKind::Error => self.config.dedupe.error,
            ReportKind::Metric => self.config.dedupe.metric,
            ReportKind::Event => self.config.dedupe.event,
            ReportKind::Healthcheck => self.config.dedupe.healthcheck,
        }
    }
}

/// Whether a report whose hash is `hash` is kept at `rate`, strictly
/// between 0 and 1 (or NaN).
fn sampled_in(rate: f32, hash: &[u8; 32]) -> bool {
    let mut bytes = [0u8; 8];
    bytes.copy_from_slice(&hash[..8]);
    let value = u64::from_le_bytes(bytes);
    let threshold = (rate * (u64::MAX as f32)) as u64;
    value <= threshold
}

/// A report's two BLAKE3 hashes, each computed the first time a step reads
/// it. `None` inside: the report could not be encoded for hashing.
#[derive(Default)]
struct ReportHashes {
    payload: Option<Option<[u8; 32]>>,
    dedupe: Option<Option<[u8; 32]>>,
}

impl ReportHashes {
    /// The hash of the report's kind, source, dedupe key and payload, which
    /// sampling and reservoirs read.
    fn payload(&mut self, report: &Report) -> Option<[u8; 32]> {
        *self.payload.get_or_insert_with(|| report_hash(report))
    }

    /// What dedupe compares: with a dedupe key, the hash of the kind, source,
    /// event and key; otherwise, or for a pooled key that cannot be
    /// resolved, the payload hash.
    fn dedupe(&mut self, report: &Report) -> Option<[u8; 32]> {
        if let Some(hash) = self.dedupe {
            return hash;
        }
        let hash = match dedupe_key_hash(report) {
            Some(hash) => Some(hash),
            None => self.payload(report),
        };
        self.dedupe = Some(hash);
        hash
    }
}

/// The hash of the report's kind, source, dedupe key and payload: the
/// structured encoding below, or, if a string of the payload cannot be
/// resolved, its JSON.
fn report_hash(report: &Report) -> Option<[u8; 32]> {
    let fast = hash_input(|input| {
        input.put(kind_tag(&report.kind).as_bytes());
        input.tagged(b"|source|", report.source.as_str().as_bytes());
        // A pooled key that cannot be resolved is left out.
        match report.dedupe_key.as_ref() {
            Some(crate::types::DedupeKey::Static(value)) => {
                input.tagged(b"|dedupe|", value.as_bytes())
            }
            Some(crate::types::DedupeKey::Pooled(slice)) => {
                if let Some(bytes) = report.payload.pool_slice(slice.start, slice.len) {
                    input.tagged(b"|dedupe|", bytes);
                }
            }
            Some(crate::types::DedupeKey::Hashed(value)) => {
                input.put(b"|dedupe-hash|");
                input.put_u64(*value);
            }
            None => {}
        }
        hash_object(input, &report.payload, report.payload.object())
    });
    if fast.is_some() {
        return fast;
    }
    let mut hasher = blake3::Hasher::new();
    report.write_json(&mut hasher).ok()?;
    Some(*hasher.finalize().as_bytes())
}

/// The hash of the kind, source, event and dedupe key; `None` without a key,
/// or for a pooled key that cannot be resolved.
fn dedupe_key_hash(report: &Report) -> Option<[u8; 32]> {
    let dedupe_key = report.dedupe_key.as_ref()?;
    hash_input(|input| {
        input.put(kind_tag(&report.kind).as_bytes());
        input.tagged(b"|source|", report.source.as_str().as_bytes());
        let event = report.payload.event_str().unwrap_or("");
        input.tagged(b"|event|", event.as_bytes());
        match dedupe_key {
            crate::types::DedupeKey::Static(value) => input.tagged(b"|key|", value.as_bytes()),
            crate::types::DedupeKey::Pooled(slice) => {
                let bytes = report.payload.pool_slice(slice.start, slice.len)?;
                input.tagged(b"|key|", bytes);
            }
            crate::types::DedupeKey::Hashed(value) => {
                input.put(b"|key-hash|");
                input.put_u64(*value);
            }
        }
        Some(())
    })
}

const HASH_INPUT_BYTES: usize = 512;

/// BLAKE3 input gathered in a buffer: hashing the encoding as a few large
/// slices costs a fraction of feeding the hasher its many small pieces. An
/// input that fits is hashed in one call; a longer one streams through a
/// hasher, a buffer at a time. Both give the hash of the bytes in order.
/// The buffer and the hasher live in the caller's frame, so neither is
/// copied.
struct HashInput<'a> {
    buf: &'a mut [u8; HASH_INPUT_BYTES],
    len: usize,
    hasher: &'a mut Option<blake3::Hasher>,
}

/// Runs `encode` on a fresh `HashInput` and returns the hash of what it
/// wrote, or `None` if it gave up.
fn hash_input(encode: impl FnOnce(&mut HashInput<'_>) -> Option<()>) -> Option<[u8; 32]> {
    let mut buf = [0u8; HASH_INPUT_BYTES];
    let mut hasher = None;
    let mut input = HashInput {
        buf: &mut buf,
        len: 0,
        hasher: &mut hasher,
    };
    encode(&mut input)?;
    let len = input.len;
    let tail = &buf[..len];
    Some(match hasher.as_mut() {
        None => *blake3::hash(tail).as_bytes(),
        Some(hasher) => *hasher.update(tail).finalize().as_bytes(),
    })
}

impl HashInput<'_> {
    #[inline]
    fn put(&mut self, bytes: &[u8]) {
        if bytes.len() > HASH_INPUT_BYTES - self.len {
            let hasher = self.hasher.get_or_insert_with(blake3::Hasher::new);
            hasher.update(&self.buf[..self.len]);
            self.len = 0;
            if bytes.len() > HASH_INPUT_BYTES {
                hasher.update(bytes);
                return;
            }
        }
        self.buf[self.len..self.len + bytes.len()].copy_from_slice(bytes);
        self.len += bytes.len();
    }

    #[inline]
    fn put_u64(&mut self, value: u64) {
        self.put(&value.to_le_bytes());
    }

    /// A tag, then the length, then the bytes: no two sequences of strings
    /// hash the same input.
    #[inline]
    fn tagged(&mut self, tag: &[u8], bytes: &[u8]) {
        self.put(tag);
        self.put_u64(bytes.len() as u64);
        self.put(bytes);
    }
}

/// Calls `f` with the text a group counts `value` as: its string form, or
/// `unknown` when it has none. Numbers are formatted on the stack.
fn with_group_text<R>(payload: &Payload, value: &Value, f: impl FnOnce(&str) -> R) -> R {
    match value {
        Value::Bool(value) => f(if *value { "true" } else { "false" }),
        Value::U64(value) => with_formatted(format_args!("{value}"), f),
        Value::I64(value) => with_formatted(format_args!("{value}"), f),
        Value::F64(value) => with_formatted(format_args!("{value}"), f),
        Value::PoolStr { start, len } => f(payload.pool_str(*start, *len).unwrap_or("unknown")),
        Value::Null | Value::RawJson { .. } => f("unknown"),
    }
}

/// Calls `f` with `args` formatted: on the stack, or in a `String` when it
/// does not fit.
fn with_formatted<R>(args: fmt::Arguments<'_>, f: impl FnOnce(&str) -> R) -> R {
    struct Text {
        buf: [u8; 64],
        len: usize,
        spilled: Option<String>,
    }
    impl fmt::Write for Text {
        fn write_str(&mut self, s: &str) -> fmt::Result {
            if let Some(spilled) = self.spilled.as_mut() {
                spilled.push_str(s);
            } else if s.len() <= self.buf.len() - self.len {
                self.buf[self.len..self.len + s.len()].copy_from_slice(s.as_bytes());
                self.len += s.len();
            } else {
                let mut spilled = String::with_capacity(self.len + s.len());
                spilled
                    .push_str(std::str::from_utf8(&self.buf[..self.len]).map_err(|_| fmt::Error)?);
                spilled.push_str(s);
                self.spilled = Some(spilled);
            }
            Ok(())
        }
    }
    let mut text = Text {
        buf: [0; 64],
        len: 0,
        spilled: None,
    };
    // Display for numbers does not fail, and the writer only on bytes it
    // wrote itself, which are whole strings.
    let _ = text.write_fmt(args);
    match text.spilled.as_deref() {
        Some(spilled) => f(spilled),
        None => f(std::str::from_utf8(&text.buf[..text.len]).unwrap_or("unknown")),
    }
}

fn generate_run_id() -> Arc<str> {
    let nanos = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_nanos();
    encode_base62(nanos)
}

fn encode_base62(mut value: u128) -> Arc<str> {
    const BASE62: &[u8; 62] = b"0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz";
    let mut buf = Vec::with_capacity(22);
    if value == 0 {
        buf.push(BASE62[0]);
    } else {
        while value > 0 {
            let rem = (value % 62) as usize;
            value /= 62;
            let digit = BASE62.get(rem).copied().unwrap_or(BASE62[0]);
            buf.push(digit);
        }
        buf.reverse();
    }
    let value = String::from_utf8(buf).expect("base62 is valid utf8");
    value.into()
}

